-- BetterForever - the settings bridge for GaarForever.
--
-- GaarForever lived in this folder until the Better...Forever family was renamed Gaar...Forever.
-- The client reads saved variables by folder name, so this small folder keeps the old name
-- only to load the old settings (BetterForeverDB).
-- Unlike the other bridges it loads after GaarForever (## Dependencies: GaarForever, 3.2.2), so
-- an old Better...Forever addon that still depends on BetterForever loads after the hub and finds
-- the library. GaarForever copies the settings into its own saved variables at this folder's
-- ADDON_LOADED (or at login) and marks the old copy (__migratedTo); nothing here runs, and
-- nothing is deleted.
--
-- Safe to delete after logging in once on each character. The bridge goes away in a later update.
